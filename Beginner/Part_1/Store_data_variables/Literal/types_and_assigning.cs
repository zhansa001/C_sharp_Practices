// Data Type	Purpose	                     Examples
// string	    Text                    	 "Hello", "Alice", "123 Main St"
// char	        A single character	         'a', 'Z', '1'
// int	        Whole numbers	             42, -5, 1000
// decimal	    Decimals	                 3.14, 9.99, -0.5
// bool	        True or false	             true, false

// How to display in console
Console.WriteLine("Marry had a little lamb");  // strings uses double quotes
Console.WriteLine('$');                       // chars uses single quote
Console.WriteLine(42);                       // int is just a number
Console.WriteLine(3.1415926);                    // decimal is same as int but with a decimal point
Console.WriteLine(true);                   // bool is just true or false

