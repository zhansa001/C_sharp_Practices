// Using Console.WriteLine()
Console.WriteLine("Hello World!");

//Escape characters
Console.WriteLine("Line 1\nLine 2"); //\n Moves new line
Console.WriteLine("Date:\t1/1/1970"); //\t Add a space
Console.WriteLine("Path:\tC:\\Users"); // \\ Just backslashes
Console.WriteLine("I said, \"Hi!\""); // \""\ Prints a double quote

//Console.Write() - Prints without making a new line break
Console.Write("Hello");
Console.Write(" ");
Console.Write("World!\n");
